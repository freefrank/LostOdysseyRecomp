bool Apply(GuestAddress e, GuestMemory &m, Registers &s) {
  if (e != 0x82a9fa40)
    return false;
  auto owner = recovery_abi::Address(s.r[3]);
  m.WriteU32(owner, 0x8204a1d8);
  for (unsigned i = 0; i < handlers.size(); ++i)
    m.WriteU32(owner + 56 + 4 * i, handlers[i]);
  m.WriteU32(owner + 44, 0);
  m.WriteU32(owner + 24, 0);
  m.WriteU8(owner + 5, 0);
  return true;
}
